#!/usr/bin/env bash

set -Eeuo pipefail

###############################################################################
# Створення нового користувача
###############################################################################

read -rp "Створити нового користувача? (y/N): " answer

if [[ "$answer" =~ ^[Yy]$ ]]; then
  read -rp "Ім’я користувача: " username
  sudo adduser "$username"
fi
